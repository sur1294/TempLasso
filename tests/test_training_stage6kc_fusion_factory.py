import pytest

from unified_bn.backbones.bqn import BQNBackboneConfig
from unified_bn.pipelines.fusion import FusionPipeline
from unified_bn.temporal.bigru import BiGRUAggregator, BiGRUConfig
from unified_bn.temporal.windowing import WindowPolicyConfig
from unified_bn.training.config import (
    CandidateRunConfig,
    RunIdentity,
    TrainingConfig,
)
from unified_bn.training.model_factory import (
    ModelFactoryError,
    build_model_from_candidate,
)
from unified_bn.training.search_space import candidate_fingerprint


def _backbone_payload() -> dict[str, object]:
    return {
        "name": "bqn",
        **asdict(
            BQNBackboneConfig(
                n_rois=100,
                n_layers=3,
                dropout=0.3,
                activation="elu",
                cluster_num=4,
            )
        ),
    }


def _temporal_payload() -> dict[str, object]:
    config = BiGRUConfig(
        input_dim=32,
        hidden_dim=32,
        num_layers=1,
        dropout=0.0,
        pooling="final",
        projection_dim=None,
        layer_norm=False,
    )
    payload = asdict(config)
    payload.pop("input_dim")
    # These are behaviorally inactive for final pooling and therefore are not
    # part of the frozen candidate identity generated by Stage 6H.
    payload.pop("attention_hidden_dim")
    payload.pop("attention_dropout")
    return {"name": "bigru", **payload}


def _fusion_candidate(
    *,
    fusion_config: dict[str, object] | None = None,
) -> CandidateRunConfig:
    return CandidateRunConfig(
        identity=RunIdentity(
            mode="fusion",
            seed=42,
            split_identity="split-sha",
            backbone_config=_backbone_payload(),
            temporal_config=_temporal_payload(),
            window_policy=WindowPolicyConfig(policy="native"),
            fusion_config=(
                {"name": "concat"}
                if fusion_config is None
                else fusion_config
            ),
        ),
        training=TrainingConfig(
            epochs=2,
            batch_size=16,
        ),
    )


def test_run_identity_accepts_and_serializes_fusion_contract() -> None:
    candidate = _fusion_candidate()
    payload = candidate.identity.to_dict()

    assert payload["mode"] == "fusion"
    assert payload["fusion_config"] == {"name": "concat"}
    assert payload["temporal_config"]["name"] == "bigru"
    assert payload["window_policy"]["policy"] == "native"


